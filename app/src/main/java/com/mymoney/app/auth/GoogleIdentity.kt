/** Verified public profile of the signed-in Google account (from Firebase Authentication). */
data class GoogleAccountInfo(
    val uid: String,
    val email: String?,
    val displayName: String?,
    val photoUrl: String?,
)

class GoogleAuthException(message: String, val cancelled: Boolean = false) : Exception(message)

/** Google Sign-In abstraction so view models and tests don't depend on Play Services. */
interface GoogleAuthGateway {
    /** False when this build has no OAuth web client id / Firebase project configured. */
    fun isConfigured(): Boolean
    /** Shows Google's account chooser, then signs in to Firebase with the returned Google ID token. */
    suspend fun signIn(activity: Activity): GoogleAccountInfo
    /** Signs out of Firebase and clears Credential Manager state so the next sign-in shows the chooser. */
    suspend fun signOut()
    /** The Firebase session persisted on this device (works offline), or null. */
    fun currentUser(): GoogleAccountInfo?
}

/** Suspends until a Play Services [Task] completes. */
suspend fun <T> Task<T>.awaitResult(): T = suspendCancellableCoroutine { cont ->
    addOnCompleteListener { t ->
        val e = t.exception
        when {
            e != null -> cont.resumeWithException(e)
            t.isCanceled -> cont.cancel()
            else -> @Suppress("UNCHECKED_CAST") cont.resume(t.result as T)
        }
    }
}

object GoogleConfig {
    /**
     * The OAuth 2.0 *web* client id used as the ID token audience. Taken from local build config, or from
     * the `default_web_client_id` string generated by the google-services plugin.
     */
    fun webClientId(context: Context): String? {
        BuildConfig.GOOGLE_WEB_CLIENT_ID.takeIf { it.isNotBlank() }?.let { return it }
        val res = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        return if (res != 0) context.getString(res).takeIf { it.isNotBlank() } else null
    }

    /** Initialises Firebase from google-services.json or from build config. Returns false if not configured. */
    fun ensureFirebase(context: Context): Boolean {
        if (FirebaseApp.getApps(context).isNotEmpty()) return true
        if (BuildConfig.FIREBASE_APP_ID.isBlank() || BuildConfig.FIREBASE_API_KEY.isBlank() || BuildConfig.FIREBASE_PROJECT_ID.isBlank()) return false
        return try {
            FirebaseApp.initializeApp(
                context,
                FirebaseOptions.Builder()
                    .setApplicationId(BuildConfig.FIREBASE_APP_ID)
                    .setApiKey(BuildConfig.FIREBASE_API_KEY)
                    .setProjectId(BuildConfig.FIREBASE_PROJECT_ID)
                    .build(),
            )
            true
        } catch (e: IllegalStateException) {
            FirebaseApp.getApps(context).isNotEmpty()
        }
    }
}

@Singleton
class FirebaseGoogleAuth @Inject constructor(@ApplicationContext private val context: Context) : GoogleAuthGateway {

    override fun isConfigured(): Boolean = GoogleConfig.webClientId(context) != null && GoogleConfig.ensureFirebase(context)

    private fun auth(): FirebaseAuth? = if (GoogleConfig.ensureFirebase(context)) FirebaseAuth.getInstance() else null

    override fun currentUser(): GoogleAccountInfo? = auth()?.currentUser?.let {
        GoogleAccountInfo(it.uid, it.email, it.displayName, it.photoUrl?.toString())
    }

    override suspend fun signIn(activity: Activity): GoogleAccountInfo {
        val clientId = GoogleConfig.webClientId(context)
            ?: throw GoogleAuthException("Google Sign-In isn't configured in this build. See README → Google Cloud setup.")
        val auth = auth() ?: throw GoogleAuthException("Firebase isn't configured in this build. See README → Firebase setup.")
        val request = GetCredentialRequest.Builder()
            // The explicit "Sign in with Google" option always shows the account chooser, which also
            // makes account switching possible.
            .addCredentialOption(GetSignInWithGoogleOption.Builder(clientId).build())
            .build()
        val credential = try {
            CredentialManager.create(activity).getCredential(activity, request).credential
        } catch (e: GetCredentialCancellationException) {
            throw GoogleAuthException("Sign-in cancelled", cancelled = true)
        } catch (e: NoCredentialException) {
            throw GoogleAuthException("No Google account is available on this device. Add one in system settings and try again.")
        } catch (e: GetCredentialException) {
            throw GoogleAuthException("Google Sign-In failed: ${e.errorMessage ?: e.type}")
        }
        if (credential !is CustomCredential ||
            (credential.type != GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL &&
                credential.type != GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_SIWG_CREDENTIAL)
        ) throw GoogleAuthException("Unexpected credential type returned")
        val google = GoogleIdTokenCredential.createFrom(credential.data)
        // Firebase verifies the ID token's signature and audience; the token itself is never stored by us.
        val user = try {
            auth.signInWithCredential(GoogleAuthProvider.getCredential(google.idToken, null)).awaitResult().user
        } catch (e: FirebaseNetworkException) {
            throw GoogleAuthException("You're offline. Connect to the internet to sign in — you can keep using My Money offline.")
        } catch (e: Exception) {
            throw GoogleAuthException("Couldn't verify your Google account: ${e.message ?: e.javaClass.simpleName}")
        } ?: throw GoogleAuthException("Couldn't verify your Google account")
        return GoogleAccountInfo(
            uid = user.uid,
            email = user.email ?: google.id,
            displayName = user.displayName ?: google.displayName,
            photoUrl = (user.photoUrl ?: google.profilePictureUri)?.toString(),
        )
    }

    override suspend fun signOut() {
        auth()?.signOut()
        try { CredentialManager.create(context).clearCredentialState(ClearCredentialStateRequest()) } catch (_: Exception) { }
    }
}
